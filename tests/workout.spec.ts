test('PWA loads and persists a session offline, with installable manifest and icons', async ({ page, context }) => {
  await page.goto('./')
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
  })
  const manifest = await (await page.request.get('manifest.webmanifest')).json()
  expect(manifest.display).toBe('standalone')
  for (const icon of manifest.icons) expect((await page.request.get(icon.src)).status()).toBe(200)
  await page.getByRole('button', { name: 'Начать тренировку' }).click()
  await page.locator('.set-check').first().click()
  await context.setOffline(true)
  await page.reload()
  // Chromium can report navigator.onLine=true after a service-worker navigation.
  // Verify a real uncached network request fails while the cached application loads.
  expect(await page.evaluate(() => fetch('./uncached-offline-probe').then(() => false, () => true))).toBe(true)
  await expect(page.getByRole('button', { name: 'Продолжить тренировку' })).toBeVisible()
  await page.getByRole('button', { name: 'Продолжить тренировку' }).click()
  await expect(page.locator('.set-check').first()).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.set-check').nth(1).click()
  await page.reload()
  await page.getByRole('button', { name: 'Продолжить тренировку' }).click()
  await expect(page.locator('.workout-progress')).toContainText('2 из 20 подходов выполнено')
})
