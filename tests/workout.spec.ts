test('clipboard denial offers selectable text, without false success or losing the session', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('./')
  await page.getByRole('button', { name: 'Начать тренировку' }).click()
  await page.locator('.set-check').first().click()
  await page.getByRole('button', { name: 'Завершить тренировку', exact: true }).click()
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Denied') } } }) })
  await page.getByRole('button', { name: 'Скопировать результаты' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Текст результатов тренировки' })).toHaveValue(/Домашняя тренировка/)
  await expect(page.getByRole('status')).not.toHaveText('Скопировано')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Выделить весь текст' }).click()
  const selection = await page.getByRole('textbox').evaluate((node: HTMLTextAreaElement) => node.selectionEnd - node.selectionStart)
  expect(selection).toBeGreaterThan(100)
  await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.getByRole('button', { name: 'Вернуться к упражнениям' }).click()
  await expect(page.locator('.set-check').first()).toHaveAttribute('aria-pressed', 'true')
})

